'use strict';

/**
 * Server-only adapters to independently provisioned, immutable assessment
 * references and human-review records. PWA reference IDs are lookup locators,
 * NOT trusted answer keys, outcomes, receipts, parent roles or grant claims.
 * A missing/unreviewed reference remains OBSERVATION_ONLY. A provider outage
 * fails centrally rather than manufacturing verified evidence.
 */
const crypto=require('node:crypto');
const Verification=require('../verification/verification-layer.js');
const VERSION='TAKY_TRUSTED_SPECIALIST_VERIFIER_PROVIDER_V1';
const clean=v=>typeof v==='string'?v.trim():'';
const norm=v=>clean(v).toLowerCase();
const hash=x=>crypto.createHash('sha256').update(JSON.stringify(x)).digest('hex');
const roles=new Set(['PARENT','TEACHER','QUALIFIED_REVIEWER']);
const matches=(row,p,identity)=>row&&row.family_id===identity.family_id&&
 row.family_id===p.context.family_id&&row.member_id===p.context.member_id&&
 row.event_id===p.event.event_id&&row.source_app===p.source_app&&
 norm(row.subject)===norm(p.context.subject)&&
 norm(row.concept_skill_target)===norm(p.context.concept_skill_target);
const asTime=v=>typeof v==='string'&&v?Date.parse(v):NaN;

function create({loadAssessment=null,loadHumanReview=null,now=Date.now}={}){
 if(loadAssessment!==null&&typeof loadAssessment!=='function')
   throw Error('SERVER_ASSESSMENT_PROVIDER_INVALID');
 if(loadHumanReview!==null&&typeof loadHumanReview!=='function')
   throw Error('SERVER_HUMAN_REVIEW_PROVIDER_INVALID');
 if(!loadAssessment&&!loadHumanReview)
   throw Error('EXPLICIT_TRUSTED_SPECIALIST_SOURCE_REQUIRED');
 if(typeof now!=='function')throw Error('TRUSTED_CLOCK_REQUIRED');

 async function verifySpecialistEvidence({packet,identity}={}){
   const p=packet;
   if(!p||!identity||identity.authenticated!==true||
      identity.family_id!==p.context?.family_id||
      !Array.isArray(identity.authorized_member_ids)||
      !identity.authorized_member_ids.includes(p.context.member_id))
     return {ok:false,reason:'TRUSTED_IDENTITY_SCOPE_REQUIRED'};
   if(p.source_app==='snap-pop'){
     if(!loadHumanReview)return {ok:false,reason:'HUMAN_REVIEW_SOURCE_NOT_CONFIGURED'};
     const review=await loadHumanReview({
       family_id:identity.family_id,member_id:p.context.member_id,
       event_id:p.event.event_id,source_app:'snap-pop'
     });
     // Review records must be generated by a separate, server-authorized
     // rubric workflow, NEVER from the browser's claimed reviewer fields.
     if(!review)return {ok:false,reason:'HUMAN_REVIEW_PENDING'};
     const reviewed=asTime(review.reviewed_at),occurred=asTime(p.event.occurred_at);
     if(!matches(review,p,identity)||
        review.authority!=='TAKY_SERVER_HUMAN_REVIEW_V1'||
        review.status!=='APPROVED'||review.reviewer_permission_checked!==true||
        !clean(review.reviewer_subject)||!roles.has(review.reviewer_role)||
        !clean(review.reference_id)||!clean(review.rubric_version)||
        ![0,1].includes(review.outcome)||!Number.isFinite(reviewed)||
        !Number.isFinite(occurred)||reviewed<occurred||reviewed>now()+60000)
       return {ok:false,reason:'SERVER_HUMAN_REVIEW_NOT_AUTHORITATIVE'};
     const issued=Verification.issueReceipt({
       receipt_id:'vr:server:'+hash(['snap',identity.family_id,p.context.member_id,
         p.event.event_id,review.reference_id,review.rubric_version]).slice(0,32),
       target_event_id:p.event.event_id,verified_at:review.reviewed_at,
       verifier_type:'HUMAN_RUBRIC_BINARY',verifier_version:review.rubric_version,
       outcome:review.outcome,member_id:p.context.member_id,
       subject:p.context.subject,concept_skill_target:p.context.concept_skill_target,
       reference_id:review.reference_id,reviewer_role:review.reviewer_role
     });
     if(!issued.ok)throw Error('SERVER_HUMAN_RECEIPT_ISSUANCE_FAILED');
     const safe=structuredClone(p);
     safe.context.verification_receipt=issued.receipt;
     return {ok:true,packet:safe};
   }
   if(!['hide-seek','ready-set'].includes(p.source_app)||!loadAssessment)
     return {ok:false,reason:'DETERMINISTIC_SOURCE_NOT_CONFIGURED'};
   const referenceId=clean(p.event?.payload?.assessment_ref);
   const response=p.event?.payload?.response_text;
   if(!referenceId||referenceId.length>128||typeof response!=='string'||
      response.length>4096)return {ok:false,reason:'SERVER_ASSIGNED_ASSESSMENT_RESPONSE_REQUIRED'};
   const reference=await loadAssessment({
     reference_id:referenceId,family_id:identity.family_id,
     member_id:p.context.member_id,event_id:p.event.event_id,
     source_app:p.source_app
   });
   if(!reference)return {ok:false,reason:'ASSESSMENT_REFERENCE_NOT_FOUND'};
   const occurred=asTime(p.event.occurred_at),issuedAt=asTime(reference.issued_at),
     expiresAt=asTime(reference.expires_at);
   if(!matches(reference,p,identity)||
      reference.authority!=='TAKY_SERVER_ASSESSMENT_REFERENCE_V1'||
      reference.status!=='ACTIVE'||reference.reference_id!==referenceId||
      reference.instrument_version!==p.event.payload.instrument_version||
      reference.match_rule!=='EXACT_NFC'||typeof reference.expected_response!=='string'||
      !Number.isFinite(occurred)||!Number.isFinite(issuedAt)||
      !Number.isFinite(expiresAt)||issuedAt>occurred||occurred>expiresAt||
      now()>=expiresAt)
     return {ok:false,reason:'ASSESSMENT_REFERENCE_NOT_AUTHORITATIVE'};
   if(p.source_app==='ready-set'&&
      p.event.payload.evidence_type!=='STRUCTURED_PRACTICE_EVIDENCE')
     return {ok:false,reason:'READY_STRUCTURED_PRACTICE_REQUIRED'};
   const verifierType=p.source_app==='hide-seek'
     ?'RETRIEVAL_EXACT_MATCH':'ANSWER_KEY_EXACT';
   const outcome=response.normalize('NFC')===
     reference.expected_response.normalize('NFC')?1:0;
   const issued=Verification.issueReceipt({
     receipt_id:'vr:server:'+hash([p.source_app,identity.family_id,
       p.context.member_id,p.event.event_id,referenceId,
       reference.instrument_version]).slice(0,32),
     target_event_id:p.event.event_id,verified_at:new Date(now()).toISOString(),
     verifier_type:verifierType,verifier_version:reference.instrument_version,
     outcome,member_id:p.context.member_id,subject:p.context.subject,
     concept_skill_target:p.context.concept_skill_target,reference_id:referenceId
   });
   if(!issued.ok)throw Error('SERVER_REFERENCE_RECEIPT_ISSUANCE_FAILED');
   const safe=structuredClone(p);
   // The current Hide adapter classifies retrieval evidence by the presence
   // of this SERVER-CREATED marker. The receipt itself is from server scoring,
   // never a local/browser candidate.
   if(p.source_app==='hide-seek')
     safe.event.payload.verification_candidate={server_reference_checked:true};
   safe.context.verification_receipt=issued.receipt;
   return {ok:true,packet:safe};
 }
 return Object.freeze({version:VERSION,verifySpecialistEvidence});
}
module.exports=Object.freeze({VERSION,create});

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {projectApproved}=require('../intake/forming-learning-projector');
const {previewApproved}=require('./forming-approved-input');
const projector=require('./build-mining-learning-pattern-registry');
const root=path.resolve(__dirname,'../..');
const ledger=JSON.parse(fs.readFileSync(path.join(root,'CURRENT/DATA/REFERENCE_INTAKE_DISPOSITION_LEDGER.json'),'utf8'));
const rules=JSON.parse(fs.readFileSync(path.join(root,'LEARNING/data/learning-reference-pattern-projection-rules-v1.json'),'utf8'));
const eligible=projector.mergeLedger(ledger.entries).filter(x=>projector.isEligible(x,rules));
assert.ok(eligible.length>0);
const sample=eligible.find(x=>projector.patternsFor(x,rules).length>0)||eligible[0];
const ref=sample.details.source_ref||'INDEX:'+sample.source_id;
const fixture={ok:true,stage:'FORMING_APPROVED_HANDOFF',eligible_for_projection:true,owner_namespace:'LEARNING_OS',forming_kind:'CONTENT_FORMING',artifact_id:'FIXTURE_ONLY',artifact_revision:'TEST',approval_evidence_ref:'FIXTURE_ONLY',index_refs:[{source_id:sample.source_id,source_ref:ref}]};
const gate=projectApproved(fixture,{ledger,rules});
assert.equal(gate.ok,true);
const scoped=previewApproved(fixture,{ledger,rules});
assert.equal(scoped.ok,true);
assert.equal(scoped.write_performed,false);
assert.equal(scoped.summary.indexed_learning_refs,1);
assert.equal(scoped.input.candidates[0].source_id,sample.source_id);
assert.equal(previewApproved({...fixture,eligible_for_projection:false},{ledger,rules}).ok,false);
const baseline=projector.build({dry_run:true});
assert.ok(baseline.registry.projection_summary.indexed_learning_refs>=1);
assert.ok(scoped.summary.indexed_learning_refs<=baseline.registry.projection_summary.indexed_learning_refs);
console.log('FORMING_REAL_LEDGER_PREVIEW_E2E 8/8 PASS; sample='+sample.source_id+'; NO CURRENT WRITE; APPROVAL FIXTURE ONLY');

'use strict';
const assert=require('node:assert/strict');
const Pipeline=require('./index-forming-learning-consumption');
const candidate={source_id:'S1',source_ref:'INDEX:S1',source_family:'REFERENCE',source_type:'DOCUMENT',authority_class:'REFERENCE',detail_anchor:'DETAIL:S1',provenance:['RAW:S1']};
const input={query_context:{consumer_app:'HIDE_SEEK',function_id:'F1',requested_behavior:'CONCEPT_SUPPORT'},candidates:[candidate]};
const verifier=(id,ref)=>({issuer:'INDEXING_OWNER',reviewed:true,decision:'INDEXED',domain_use_authorized:true,source_id:id,source_ref:ref,index_version:'V1',review_evidence_refs:['REVIEW:1'],source_family:candidate.source_family,source_type:candidate.source_type,authority_class:candidate.authority_class,detail_anchor:candidate.detail_anchor,provenance:candidate.provenance});
const options={owner_namespace:'LEARNING_OS',forming_kind:'CONTENT_FORMING',target_consumer:'HIDE_SEEK',ruleset_revision:'R1'};
const success=Pipeline.prepare(input,verifier,options);
assert.equal(success.ok,true);
assert.equal(success.stage,'FORMING_DRAFT');
assert.equal(success.formed.status,'DRAFT');
assert.equal(success.projection_eligible,false);
assert.equal(success.formed.approval_status,'UNAPPROVED');
assert.deepEqual(success.formed.source_refs,['INDEX:S1']);
assert.equal(Pipeline.prepare(input,null,options).stage,'INDEXING');
assert.equal(Pipeline.prepare(input,verifier,{...options,forming_kind:'BAD'}).stage,'FORMING');
assert.deepEqual(Pipeline.prepare(input,verifier,options),success);
const left={type:'CONCEPT_LINK',target:'A',anchor:'DETAIL:S1'};
const right={...left,target:'B'};
const withLink=link=>({...input,candidates:[{...candidate,relations:[link]}]});
const verifyLink=link=>(id,ref)=>({...verifier(id,ref),relations:[link]});
const first=Pipeline.prepare(withLink(left),verifyLink(left),options);
const second=Pipeline.prepare(withLink(right),verifyLink(right),options);
assert.equal(first.ok,true);
assert.equal(second.ok,true);
assert.notEqual(first.formed.artifact_revision,second.formed.artifact_revision);
assert.deepEqual(first.formed.index_refs[0].relations,[left]);
const spoof=Pipeline.prepare(withLink(right),verifyLink(left),options);
assert.equal(spoof.ok,false);
assert.equal(spoof.stage,'INDEXING');
console.log('INDEX_FORMING_LEARNING_CONSUMPTION: owner-backed semantic continuity PASS');
const duplicate=Pipeline.prepare({...input,candidates:[candidate,candidate]},verifier,options);
assert.equal(duplicate.ok,false);
assert.equal(duplicate.stage,'INDEXING');
assert.deepEqual(duplicate.issues,['SOURCE_ID_DUPLICATE:1','SOURCE_REF_DUPLICATE:1']);
assert.equal(Object.hasOwn(duplicate,'formed'),false);
assert.equal(Object.hasOwn(duplicate,'indexed'),false);

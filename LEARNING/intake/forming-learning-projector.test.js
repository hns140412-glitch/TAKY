'use strict';
const assert=require('node:assert/strict');
const {projectApproved}=require('./forming-learning-projector');
const rules={schema:'TAKY_LEARNING_REFERENCE_PATTERN_PROJECTION_RULES_V1',eligibility:{state:'EVIDENCE_CANDIDATE',domain:'education',consumer:'LEARNING_ENGINE'},signal_to_patterns:{VISUAL_CONCEPT_CARD:['P_VISUAL_CONCEPT_CARD']},scope_to_patterns:{}};
const ledger={schema:'TAKY_REFERENCE_INTAKE_DISPOSITION_LEDGER_V1',entries:[{source_key:'S1',state:'EVIDENCE_CANDIDATE',acquisition_state:'COMPLETE',recorded_at:'2026-10-12',details:{source_id:'S1',source_ref:'INDEX:S1',domain:'education',consumer:'LEARNING_ENGINE',source_direction_signals:['VISUAL_CONCEPT_CARD']}}]};
const handoff={ok:true,stage:'FORMING_APPROVED_HANDOFF',eligible_for_projection:true,owner_namespace:'LEARNING_OS',forming_kind:'CONTENT_FORMING',artifact_id:'A',artifact_revision:'R',approval_evidence_ref:'E',index_refs:[{source_id:'S1',source_ref:'INDEX:S1'}]};
const opts={rules,ledger};
const good=projectApproved(handoff,opts);
assert.equal(good.ok,true);
assert.equal(good.stage,'LEARNING_PATTERN_PROJECTION_CANDIDATE');
assert.equal(good.write_performed,false);
assert.equal(good.learning_engine_decision,null);
assert.equal(good.candidates[0].source_id,'S1');
assert.equal(projectApproved({...handoff,ok:false},opts).ok,false);
assert.equal(projectApproved({...handoff,owner_namespace:'OTHER'},opts).ok,false);
assert.equal(projectApproved({...handoff,forming_kind:'APPLICATION_FORMING'},opts).ok,false);
assert.equal(projectApproved({...handoff,index_refs:[{source_id:'S1',source_ref:'OTHER'}]},opts).ok,false);
assert.equal(projectApproved(handoff,{rules,ledger:{...ledger,entries:[]}}).ok,false);
assert.equal(projectApproved(handoff,{rules:{...rules,schema:'BAD'},ledger}).ok,false);
console.log('FORMING_LEARNING_PROJECTOR: 11/11 PASS');
